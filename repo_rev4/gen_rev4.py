"""Generates numbers_rev4.tex, tables/tab_tuning.tex and tables/tab_descriptives.tex from results_rev4/*.csv.
Usage: python gen_rev4.py <results_rev4 dir> <manuscript dir>"""
import sys, os, pandas as pd, numpy as np
res, ms = sys.argv[1], sys.argv[2]
S = pd.read_csv(os.path.join(res, "summary_rev4.csv")); C = pd.read_csv(os.path.join(res, "tuned_vs_default.csv"))
W = pd.read_csv(os.path.join(res, "wins_tuned.csv")); D = pd.read_csv(os.path.join(res, "descriptives.csv"))
DS = {"COCOMO81": "coc", "NASA93": "nasa", "Desharnais": "des"}; SP = {"semilog": "Semi", "loglog": "LL"}
ALG = ["LR", "DT", "RF", "KNN", "SVR", "GB"]
NAMES = {"LR": "Linear Regression", "DT": "Decision Tree", "RF": "Random Forest", "KNN": "KNN", "SVR": "SVR", "GB": "Gradient Boosting"}
f1 = lambda v: f"{v:,.1f}"
def cell(ds, sp, a, arm, col="MAE_mean10"):
    r = S[(S.dataset == ds) & (S.spec == sp) & (S.algorithm == a) & (S.arm == arm)]
    return None if r.empty else float(r[col].iloc[0])
L = ["% AUTO-GENERATED by gen_rev4.py from results_rev4/*.csv (sensitivity analysis, fourth revision round). Do not edit by hand."]
trace = []
def mac(name, val, src):
    L.append(f"\\newcommand{{\\{name}}}{{{val}}}"); trace.append((name, val, src))
for ds, d in DS.items():
    for sp, s in SP.items():
        for a in ALG:
            for arm, t in (("default", "D"), ("tuned", "T")):
                v = cell(ds, sp, a, arm)
                if v is None: continue
                mac(f"Mae{t}{a}{d}{s}", f1(v), f"summary_rev4.csv MAE_mean10 [{ds},{sp},{a},{arm}]")
                mac(f"Pred{t}{a}{d}{s}", f1(cell(ds, sp, a, arm, "PRED25_mean10")), f"summary_rev4.csv PRED25_mean10 [{ds},{sp},{a},{arm}]")
        for a in ALG:
            if a == "LR": continue
            r = C[(C.dataset == ds) & (C.spec == sp) & (C.algorithm == a)].iloc[0]
            mac(f"Chg{a}{d}{s}", f"{abs(r.change_percent):.1f}", f"tuned_vs_default.csv |change_percent| [{ds},{sp},{a}] (sign: {'+' if r.change_percent>0 else '-'})")
        w = W[(W.dataset == ds) & (W.spec == sp)].iloc[0]
        for a in ALG:
            mac(f"Win{a}{d}{s}", int(w[a]), f"wins_tuned.csv [{ds},{sp},{a}]")
# aggregates used in the text
nonsvr = C[C.algorithm != "SVR"]["change_percent"].abs().max(); svr = C[C.algorithm == "SVR"]["change_percent"]
mac("ChgMaxNonSVR", f"{nonsvr:.1f}", "tuned_vs_default.csv max |change_percent| over DT, RF, KNN, GB")
mac("ChgMaxSVRdown", f"{abs(svr.min()):.1f}", "tuned_vs_default.csv largest decrease, SVR"); mac("ChgMaxSVRup", f"{svr.max():.1f}", "tuned_vs_default.csv largest increase, SVR")
rf = C[C.algorithm == "RF"]; mac("RFtunedHigher", int((rf.change_percent > 0).sum()), "tuned_vs_default.csv RF rows with change_percent > 0 (of 6)")
best = S.loc[S.PRED25_mean10.idxmax()]
mac("BestPREDsens", f1(best.PRED25_mean10), f"summary_rev4.csv max PRED25_mean10 = [{best.dataset},{best.spec},{best.algorithm},{best.arm}]")
open(os.path.join(ms, "numbers_rev4.tex"), "w").write("\n".join(L) + "\n")

# ---- Table: MAE default vs tuned
rows = []
cols = [("semilog", "default"), ("semilog", "tuned"), ("loglog", "default"), ("loglog", "tuned")]
for i, ds in enumerate(DS):
    mins = {}
    for sp, arm in cols:
        vals = [cell(ds, sp, a, arm) if not (a == "LR" and arm == "tuned") else cell(ds, sp, a, "default") for a in ALG]
        mins[(sp, arm)] = min(round(v, 1) for v in vals)
    for j, a in enumerate(ALG):
        cs = []
        for sp, arm in cols:
            src_arm = "default" if a == "LR" else arm      # LR has no hyperparameter: its values are repeated
            m, sd = cell(ds, sp, a, src_arm), cell(ds, sp, a, src_arm, "MAE_sd10")
            ms_ = f1(m); ms_ = f"\\textbf{{{ms_}}}" if round(m, 1) == mins[(sp, arm)] else ms_
            cs.append(f"{ms_} $\\pm$ {f1(sd)}")
        lead = f"\\multirow{{6}}{{*}}{{{ds}}}" if j == 0 else ""
        rows.append(f"{lead} & {NAMES[a]} & " + " & ".join(cs) + " \\\\")
    if i < 2: rows.append("\\midrule")
open(os.path.join(ms, "tables", "tab_tuning.tex"), "w").write("\n".join(rows) + "\n")

# ---- Table: dataset descriptives
SIZE = {"COCOMO81": "KLOC", "NASA93": "KLOC", "Desharnais": "function points"}; UNIT = {"COCOMO81": "person-months", "NASA93": "person-months", "Desharnais": "person-hours"}
PROJ = {"COCOMO81": "63", "NASA93": "93", "Desharnais": "81 (77 used)"}
g = lambda v: f"{v:,.0f}" if abs(v - round(v)) < 1e-9 else f"{v:,.1f}"   # 1,150 / 47.5
def sk(v):
    t = f"{v:.2f}"
    if t == "-0.00": t = "0.00"
    return "$-$" + t[1:] if t.startswith("-") else t
rows = []
for r in D.itertuples():
    assert (r.dataset != "Desharnais" and str(r.n) == PROJ[r.dataset]) or (r.dataset == "Desharnais" and r.n == 77)
    rows.append(f"{r.dataset} & {PROJ[r.dataset]} & {r.features} & {SIZE[r.dataset]} & {g(r.size_min)} & {g(r.size_median)} & {g(r.size_max)} & {UNIT[r.dataset]} & {g(r.effort_min)} & {g(r.effort_median)} & {g(r.effort_mean)} & {g(r.effort_max)} & {sk(r.skewness)} & {sk(r.skewness_log1p)} \\\\")
open(os.path.join(ms, "tables", "tab_descriptives.tex"), "w").write("\n".join(rows) + "\n")
pd.DataFrame(trace, columns=["macro", "value", "source"]).to_csv(os.path.join(ms, "..", "NUMBER_TRACE_rev4.csv"), index=False)
print(len(L) - 1, "macros")
